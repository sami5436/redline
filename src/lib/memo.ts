import type { Claim, Report, Source } from "./types";

interface Index {
  claim: (id: string) => Claim | undefined;
  source: (id: string) => Source | undefined;
}

/** Render a report as a shareable Markdown diligence memo with footnoted evidence. */
export function toMarkdown(report: Report, ev: Index, provider: string): string {
  const cited = [
    ...new Set([...report.redFlags, ...report.strengths, ...report.contradictions].flatMap((x) => x.evidence)),
  ];
  const cite = (ids: string[]) => ids.map((id) => `[${id}]`).join("");
  return [
    `# Diligence memo: ${report.subject}`,
    "",
    `**Risk ${report.riskScore}/100.** ${report.verdict}`,
    "",
    report.summary,
    "",
    "## Red flags",
    ...report.redFlags.map(
      (f) => `- **${f.severity.toUpperCase()}: ${f.title}.** ${f.explanation} ${cite(f.evidence)} _(${f.corroboration} independent domain${f.corroboration === 1 ? "" : "s"})_`,
    ),
    "",
    ...(report.contradictions.length
      ? ["## Contradictions", ...report.contradictions.map((c) => `- ${c.summary} ${cite(c.evidence)}`), ""]
      : []),
    ...(report.mitigations.length
      ? ["## Deal protections", ...report.mitigations.map((m, i) => `${i + 1}. ${m.action}${m.addresses ? ` _(${m.addresses})_` : ""}`), ""]
      : []),
    "## Strengths",
    ...report.strengths.map((s) => `- ${s.point} ${cite(s.evidence)}`),
    "",
    "## Still to verify",
    ...report.openQuestions.map((q) => `- ${q}`),
    "",
    "## Evidence",
    ...cited.map((id) => {
      const c = ev.claim(id);
      const s = c && ev.source(c.sourceId);
      return `- **[${id}]** ${c?.text ?? ""} ([${s?.title ?? c?.sourceId}](${s?.url ?? ""}))`;
    }),
    "",
    `_Generated by Redline: NVIDIA Nemotron via ${provider || "Nebius Token Factory"}, web research by Tavily. A research aid, not legal or financial advice._`,
  ].join("\n");
}
